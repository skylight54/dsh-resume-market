/**
 * 构建客户端 bundle：把 src/client/*.js 与 src/shared/doc.js 拼进
 * window.__ModuleLoader__.load 的 factory 里，零运行时依赖。
 *
 * 用法：node build/build.mjs
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const PKG = JSON.parse(await readFile(join(ROOT, 'package.json'), 'utf8'));

/** 客户端文件顺序：doc.js 的共享层在视图之前，入口最后。 */
const FILES = [
  'src/shared/doc.js',
  'src/client/00-preface.js',
  'src/client/10-css.js',
  'src/client/20-docview.js',
  'src/client/30-market.js',
  'src/client/40-editor.js',
  'src/client/45-resumes.js',
  'src/client/55-pdf.js',
  'src/client/50-panel.js',
  'src/client/60-chat.js',
  'src/client/70-entry.js',
];

const ALLOWED_REQUIRES = new Set(['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client']);

const chunks = [];
const hash = createHash('sha256');
const seen = [];

for (const rel of FILES) {
  const abs = join(ROOT, rel);
  let code = await readFile(abs, 'utf8');
  if (rel.endsWith('doc.js')) {
    // 共享层用 ESM 导出，内联时去掉 `export` 关键字即可（只允许具名 export）。
    code = code.replace(/^export\s+(?=(const|let|var|function|class))/gm, '');
    // 末尾的 `export { ... };` 具名导出块同样去掉（仅 Host 用，客户端内联时不需要）。
    code = code.replace(/^export\s*\{[\s\S]*?\};\s*$/gm, '');
    if (/^export\s+default/m.test(code)) {
      throw new Error(rel + ': 不支持 export default');
    }
  }
  if (/^\s*(import|export)\s/m.test(code)) {
    throw new Error(rel + ': client 代码里不允许出现 import/export（doc.js 请用 export const/function）');
  }
  const requires = [...code.matchAll(/require\(\s*['"]([^'"]+)['"]\s*\)/g)].map((m) => m[1]);
  for (const name of requires) {
    if (!ALLOWED_REQUIRES.has(name)) throw new Error(rel + ': 不允许 require("' + name + '")');
  }
  chunks.push('/*** ' + rel + ' ***/\n' + code);
  hash.update(code);
  seen.push(rel);
}

const body = chunks.join('\n\n');
// 只编译不执行，提前暴露语法错误。
try {
  new Function('require', 'module', 'exports', body);
} catch (err) {
  throw new Error('拼接后的客户端代码存在语法错误：' + err.message);
}

const bundle =
  '/* dsh-plugin-resume-market client bundle, generated by build/build.mjs */\n' +
  'window.__ModuleLoader__.load({\n' +
  '  id: ' + JSON.stringify(PKG.name) + ',\n' +
  '  factory(require) {\n' +
  "    'use strict';\n" +
  '    var module = { exports: {} };\n' +
  body +
  '\n    return module.exports;\n' +
  '  },\n' +
  '});\n';

await mkdir(join(ROOT, 'lib'), { recursive: true });
await writeFile(join(ROOT, 'lib', 'client.js'), bundle, 'utf8');
await writeFile(
  join(ROOT, 'lib', 'client.meta.json'),
  JSON.stringify(
    {
      id: PKG.name,
      version: PKG.version,
      files: seen,
      sha256: hash.digest('hex'),
      bytes: Buffer.byteLength(bundle, 'utf8'),
      builtAt: new Date().toISOString(),
    },
    null,
    2
  ) + '\n',
  'utf8'
);

console.log('✅ lib/client.js  ' + Buffer.byteLength(bundle, 'utf8') + ' bytes  (' + seen.length + ' files)');
